<?php

declare(strict_types=1);

namespace App\Tests\Unit\Host;

use PHPUnit\Framework\Attributes\Group;
use PHPUnit\Framework\TestCase;
use Symfony\Component\Filesystem\Filesystem;

/**
 * htdocs/include/requirements.php: the PHP version check that runs before
 * anything that needs a newer PHP version.
 */
#[Group('spec:host-deployment')]
final class PhpRequirementTest extends TestCase
{
    private string $dir;
    private string $root;
    private string $trust;

    public static function setUpBeforeClass(): void
    {
        require_once dirname(__DIR__, 3) . '/htdocs/include/requirements.php';
    }

    protected function setUp(): void
    {
        $this->dir = str_replace('\\', '/', sys_get_temp_dir()) . '/icms-php-' . bin2hex(random_bytes(4));
        $this->root = $this->dir . '/www';
        $this->trust = $this->dir . '/trust';
        (new Filesystem())->mkdir([$this->root, $this->trust]);
        putenv('ICMS_MAINFILE');
    }

    protected function tearDown(): void
    {
        (new Filesystem())->remove($this->dir);
    }

    /**
     * @scenario Minimum version from Composer
     */
    public function testTheMinimumComesFromTheComposerPlatformCheckOfTheVendorDirectoryInUse(): void
    {
        self::assertNull(icms_php_requirement($this->root), 'no vendor directory');

        $this->writeVendor($this->root . '/vendor', null);
        self::assertNull(icms_php_requirement($this->root), 'platform check turned off');

        $this->writeVendor($this->root . '/vendor', 70400);
        self::assertSame(70400, icms_php_requirement($this->root));

        $this->writeVendor($this->root . '/trust_dist/vendor', 80100);
        self::assertSame(80100, icms_php_requirement($this->root), 'the staging directory comes before the web root');

        file_put_contents($this->root . '/mainfile.php', "<?php\ndefine('XOOPS_TRUST_PATH', '{$this->trust}');\n");
        $this->writeVendor($this->trust . '/vendor', 80200);
        self::assertSame(80200, icms_php_requirement($this->root), 'the trust path comes first');
    }

    /**
     * @scenario Minimum version from Composer
     */
    public function testTheRealPlatformCheckIsUnderstood(): void
    {
        // the repository root is the trust path of a development checkout
        $check = (string) file_get_contents(dirname(__DIR__, 3) . '/vendor/composer/platform_check.php');
        self::assertMatchesRegularExpression('/PHP_VERSION_ID >= \d+/', $check);

        (new Filesystem())->dumpFile($this->root . '/vendor/autoload.php', "<?php\n");
        (new Filesystem())->dumpFile($this->root . '/vendor/composer/platform_check.php', $check);
        self::assertGreaterThanOrEqual(80200, icms_php_requirement($this->root));
    }

    /**
     * @scenario PHP older than the packages need
     */
    public function testAnOlderPhpGetsTheRequirementsPageWithBothVersions(): void
    {
        $this->writeVendor($this->root . '/trust_dist/vendor', 80200);
        copy(dirname(__DIR__, 3) . '/htdocs/requirements.html', $this->root . '/requirements.html');

        $page = (string) icms_requirements_page($this->root, 70433, '7.4.33');

        self::assertStringContainsString('PHP 7.4.33', $page);
        self::assertStringContainsString('PHP 8.2.0 or newer', $page);
        self::assertStringNotContainsString('<!--icms:', $page, 'every placeholder is filled in');
    }

    /**
     * @scenario PHP older than the packages need
     */
    public function testThePageWorksWithoutTheHtmlFile(): void
    {
        $this->writeVendor($this->root . '/vendor', 80301);

        $page = (string) icms_requirements_page($this->root, 80200, '8.2.0<script>');

        self::assertStringContainsString('PHP 8.3.1 or newer', $page);
        self::assertStringContainsString('8.2.0&lt;script&gt;', $page);
    }

    /**
     * @scenario Supported PHP version
     */
    public function testASupportedPhpRunsAsUsual(): void
    {
        $this->writeVendor($this->root . '/vendor', 80200);

        self::assertNull(icms_requirements_page($this->root, 80200, '8.2.0'));
        self::assertNull(icms_requirements_page($this->root, PHP_VERSION_ID, PHP_VERSION));
        self::assertNull(icms_requirements_page($this->dir . '/empty', 50600, '5.6.40'), 'no known minimum');
    }

    private function writeVendor(string $vendor, ?int $minimum): void
    {
        $fs = new Filesystem();
        $fs->dumpFile($vendor . '/autoload.php', "<?php\n");
        if ($minimum === null) {
            $fs->remove($vendor . '/composer/platform_check.php');

            return;
        }
        $version = sprintf('%d.%d.%d', intdiv($minimum, 10000), intdiv($minimum, 100) % 100, $minimum % 100);
        $fs->dumpFile($vendor . '/composer/platform_check.php', <<<PHP
            <?php

            // platform_check.php @generated by Composer

            \$issues = array();

            if (!(PHP_VERSION_ID >= {$minimum})) {
                \$issues[] = 'Your Composer dependencies require a PHP version ">= {$version}". You are running ' . PHP_VERSION . '.';
            }
            PHP);
    }
}
